// Turn the tracked takes into shelf moves (motion library from free clips,
// 3 Nov 2026): characters/moves/acted/clips.json (one row per clip, with the
// move's name, phrases, hands and face) + takes/<id>.json → acted/shelf.mjs.
//   node tools/acted-shelf.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeTake, takeToMove, activeSpan } from "../characters/core/acted.mjs";
import { normalizeMove } from "../characters/core/moves.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "characters/moves/acted");
const clips = JSON.parse(fs.readFileSync(path.join(dir, "clips.json"), "utf8"));
const TORSO = 0.3; // close to every drawn figure's shoulder-to-hip; the move is in angles anyway
const out = [], quality = {}, preview = {};
// how much of the person the tracker really saw: both arms (shoulder, elbow, wrist) and both feet
const seen = (take, idx) => take.frames.filter((f) => idx.every((i) => (f.lm[i]?.[2] ?? 0) > 0.5)).length / take.frames.length;
for (const c of clips) {
  if (c.drop) continue;
  const f = path.join(dir, "takes", c.id + ".json");
  if (!fs.existsSync(f)) { console.log(`${c.id}: no take yet`); continue; }
  const { take, problems } = normalizeTake(JSON.parse(fs.readFileSync(f, "utf8")));
  if (!take || take.frames.length < 8) { console.log(`${c.id}: unusable take (${problems.join("; ") || "too few frames"})`); continue; }
  const q = { frames: take.frames.length, arms: +seen(take, [11, 12, 13, 14, 15, 16]).toFixed(2), feet: +seen(take, [27, 28]).toFixed(2) };
  quality[c.id] = q;
  if (q.arms < 0.5) { console.log(`${c.id}: skipped, arms seen in only ${Math.round(q.arms * 100)}% of frames`); continue; }
  const mv = takeToMove(take, {
    id: c.move ?? c.id, name: c.name ?? c.action, help: c.help ?? `Copied from a real person: ${c.action}.`,
    kind: c.kind ?? "gesture", tags: c.tags ?? [], phrases: c.phrases ?? [], hands: c.hands, face: c.face,
    inMs: c.inMs, outMs: c.outMs, legs: c.legs ?? (q.feet > 0.8 ? "auto" : false), sit: c.sit ?? "auto", torso: TORSO,
  });
  const r = normalizeMove(mv);
  if (r.problems.length) console.log(`${c.id}: ${r.problems.join("; ")}`);
  out.push(mv);
  // the source as a stick figure for the library page: 13 points at 15 fps over the move's stretch
  const keep = [0, 11, 12, 13, 14, 15, 16, 23, 24, 25, 26, 27, 28], step = Math.max(1, Math.round(take.fps / 15));
  const sp = c.inMs !== undefined ? { inMs: c.inMs, outMs: c.outMs } : activeSpan(take, { torso: TORSO });
  preview[mv.id] = { aspect: take.aspect ?? 1, mirrored: !!take.mirrored, f: take.frames.filter((f, i) => i % step === 0 && f.ms >= sp.inMs && f.ms <= sp.outMs).map((f) => keep.map((k) => [Math.round(f.lm[k][0] * 1000), Math.round(f.lm[k][1] * 1000)])) };
  console.log(`${c.id}: ${(mv.lengthMs / 1000).toFixed(1)} s, ${Object.keys(mv.tracks).join(" ")}`);
}
const src = `// GENERATED by tools/acted-shelf.mjs from characters/moves/acted (clips.json + takes).
// Moves from real motion capture: CMU Graphics Lab (free for all uses, never resell the data) and
// Quaternius Universal Animation Library (CC0). 3 Nov 2026.
// Do not edit by hand: change clips.json and run the tool again.
export const ACTED_DATA = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(dir, "shelf.mjs"), src);
fs.writeFileSync(path.join(dir, "quality.json"), JSON.stringify(quality, null, 1));
fs.writeFileSync(path.join(dir, "preview.json"), JSON.stringify(preview));
console.log(`wrote characters/moves/acted/shelf.mjs: ${out.length} moves, ${Math.round(src.length / 1024)} KB`);
